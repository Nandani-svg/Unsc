import Anthropic from "@anthropic-ai/sdk";


export const config = { maxDuration: 120 };

const MAX_IMAGE_BYTES = 3_500_000; // base64 length, keeps under Vercel's 4.5 MB body limit
const MEDIA = new Set(["image/jpeg", "image/png", "image/webp", "image/gif"]);

const AGENDA = "Addressing the Expansion of Proxy Warfare Through State-Sponsored Non-State Armed Groups and Private Military Actors and Its Implications for International Peace and Security";

