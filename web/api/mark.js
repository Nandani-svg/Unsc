function parseJson(text) {
  try { return JSON.parse(text); } catch {}
  const fence = text.match(/```(?:json)?\s*([\s\S]*?)```/);
  if (fence) { try { return JSON.parse(fence[1]); } catch {} }
  const s = text.indexOf("{"), e = text.lastIndexOf("}");
  if (s >= 0 && e > s) { try { return JSON.parse(text.slice(s, e + 1)); } catch {} }
  return null;
}

export default async function handler(req, res) {
  if (req.method !== "POST") { res.setHeader("Allow", "POST"); return res.status(405).json({ code: "method", message: "Use POST." }); }
  const need = process.env.ACCESS_CODE;
  if (need && req.headers["x-access-code"] !== need) {
    return res.status(401).json({ code: "access_code", message: "Wrong or missing committee access code." });
  }
  if (!process.env.ANTHROPIC_API_KEY) {
    return res.status(500).json({ code: "no_key", message: "The server has no ANTHROPIC_API_KEY set in Vercel." });
  }
  const body = req.body || {};
  const typed = typeof body.typed === "string" ? body.typed.slice(0, 6000).trim() : "";
  const forced = ["auto", "normal", "substantive"].includes(body.forcedType) ? body.forcedType : "auto";
  const image = body.image && typeof body.image.data === "string" ? body.image : null;
  if (image && (!MEDIA.has(image.mediaType) || image.data.length > MAX_IMAGE_BYTES)) {
    return res.status(400).json({ code: "image_rejected", message: "Image must be a JPG, PNG, WebP or GIF under about 2.5 MB." });
  }
  if (!image && !typed) return res.status(400).json({ code: "empty", message: "Send a chit image or typed text." });

  const content = [];
  if (image) content.push({ type: "image", source: { type: "base64", media_type: image.mediaType, data: image.data } });
  content.push({ type: "text", text: buildPrompt(typed, forced, !!image) });

  try {
    const client = new Anthropic(); // reads ANTHROPIC_API_KEY from the Vercel environment
    const response = await client.beta.messages.create({
      model: "claude-opus-5-5",
      max_tokens: 8000,
      output_config: { effort: "medium" },
      betas: ["server-side-fallback-2026-07-01"],
      fallbacks: "default",
      messages: [{ role: "user", content }],
    });
    if (response.stop_reason === "refusal") {
      return res.status(422).json({ code: "refused", message: "Claude would not mark this input." });
    }
    const text = response.content.filter((b) => b.type === "text").map((b) => b.text).join("");
    const ev = parseJson(text);
    if (!ev || typeof ev !== "object") return res.status(502).json({ code: "invalid_json", message: "The reply came back malformed." });
    return res.status(200).json({ ev });
  } catch (error) {
    if (error instanceof Anthropic.AuthenticationError) return res.status(500).json({ code: "bad_key", message: "The Anthropic API key on the server is invalid." });
    if (error instanceof Anthropic.RateLimitError) return res.status(429).json({ code: "rate_limited", message: "Rate limited." });
    if (error instanceof Anthropic.BadRequestError) return res.status(400).json({ code: "bad_request", message: error.message });
    if (error instanceof Anthropic.APIError) return res.status(502).json({ code: "upstream_error", message: `API error ${error.status}` });
    return res.status(502).json({ code: "upstream_error", message: "Could not reach Claude." });
  }
}
